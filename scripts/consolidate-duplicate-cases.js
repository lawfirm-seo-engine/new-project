import fs from "node:fs/promises";
import path from "path";
import { CASE_SLUG_REDIRECTS, canonicalCaseSlug } from "../functions/_caseAliases.js";
import { normalizeCaseIdentity } from "../functions/_caseIdentity.js";
import { mergeDuplicateCase } from "../functions/_caseMerge.js";

const root = process.cwd();
const dataPath = path.join(root, "data", "cases.json");
const generatedIndexPath = path.join(root, "functions", "_caseNameIndex.generated.js");
const apply = process.argv.includes("--write");
const cases = JSON.parse(await fs.readFile(dataPath, "utf8"));
const bySlug = new Map(cases.filter((item) => item?.slug).map((item) => [item.slug, item]));
const merged = [];
const missing = [];

for (const [duplicateSlug, winnerSlug] of Object.entries(CASE_SLUG_REDIRECTS)) {
  const duplicate = bySlug.get(duplicateSlug);
  const winner = bySlug.get(winnerSlug);
  if (!duplicate || !winner) {
    if (duplicate || !winner) missing.push({ duplicateSlug, winnerSlug, duplicate: Boolean(duplicate), winner: Boolean(winner) });
    continue;
  }
  const next = mergeDuplicateCase(winner, duplicate);
  bySlug.set(winnerSlug, next);
  bySlug.delete(duplicateSlug);
  merged.push({ duplicateSlug, winnerSlug, caseName: next.caseName });
}

const nextCases = cases
  .filter((item) => !CASE_SLUG_REDIRECTS[item.slug])
  .map((item) => bySlug.get(item.slug) || item);

const nameIndex = {};
for (const item of nextCases) {
  const identity = normalizeCaseIdentity(item.caseName || item.name || item.title);
  if (!identity || !item?.slug) continue;
  nameIndex[identity] = canonicalCaseSlug(item.slug);
}

const generated = [
  "// Generated by scripts/consolidate-duplicate-cases.js. Do not edit manually.",
  `export const STATIC_CASE_NAME_INDEX = Object.freeze(${JSON.stringify(nameIndex, null, 2)});`,
  "",
].join("\n");

if (apply) {
  await fs.writeFile(dataPath, `${JSON.stringify(nextCases, null, 2)}\n`, "utf8");
  await fs.writeFile(generatedIndexPath, generated, "utf8");
}

console.log(JSON.stringify({
  apply,
  before: cases.length,
  after: nextCases.length,
  merged: merged.length,
  aliases: Object.keys(CASE_SLUG_REDIRECTS).length,
  identities: Object.keys(nameIndex).length,
  missing,
}, null, 2));

if (missing.length) process.exitCode = 1;
